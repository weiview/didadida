-- 0031：`Photo.file_size` —— 重複視窗上給人判斷用的「檔案大小」
--
-- ## 為什麼要
-- 同一張照片從手機（App）傳跟從電腦（網頁）傳，`file_hash` 必定對不上 ——
-- 那個雜湊算的是**上傳進來的那顆 800px 縮圖的位元組**，而兩邊的編碼器不同
-- （瀏覽器 libwebp vs Android 的 encoder），位元組層級一模一樣是做不到的。
-- 所以跨平台的重複改由 `phash`（畫面本身）認出來，而 phash 只說「看起來一樣」，
-- 連拍也會長得一樣 —— 最後一步永遠要人看一眼。檔名已經在視窗上了，
-- 再補一個檔案大小，同一台相機的同一個檔大小會一樣，是人當場判斷得了的線索。
--
-- ## 為什麼不去 R2 問
-- `HEAD` 一顆物件是一次 class B 操作（每一列、每一次開視窗），而且它回的是
-- **那顆 800px 縮圖**的大小，不是使用者手上那個原始檔 —— 兩個數字不能比，
-- 擺在一起只會誤導。所以改成上傳時由前端／App 把原始檔大小送上來。
--
-- ## 沒有 DEFAULT，也不 backfill
-- 既有的每一列留在 NULL＝「不知道」，畫面上就不寫這一格（不是寫 0）。
-- 原始檔從來不經過 Worker（直傳 Drive），後端補不出這個值，
-- 對 prod 做大 backfill 也不在免費額度的預算裡。
ALTER TABLE Photo ADD COLUMN file_size INTEGER;
