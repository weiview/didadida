-- 0016：白名單加上「這個人能不能用管理工具」。
--
-- 0009 把軌跡改成每人各自一份之後，/map 的工具區對**所有登入的成員**開放：
-- Google 時間軸匯入、立即同步足跡、手動上傳 GPX，還有進頁面就自動跑的同步與貼路。
-- 後端那 10 支端點也只擋 guardTrackAccess ——「看得到地圖」就等於「寫得進去」。
--
-- 看與寫是兩件事。家人裡不是每個人都需要（也不是每個人都該）去動 Drive 同步、
-- 覆蓋整天的軌跡、上傳時間軸。這一欄把寫入那一半切出來。
--
-- ## 粒度沿用既有的，不另創第三套
--
--   can_use_tools  每人一欄（就是這裡）。同 0010／0013／0014 的理由：站長要能單獨關掉某一個人
--
-- ## 預設 1（開）
--
-- 跟 can_comment／can_view_comments／can_view_map 一樣。現況就是所有成員都能用，
-- 預設 0 等於這次 migration 一套下去全家人的工具區同時消失，那是改壞不是改對。
-- **新加入的人則預設不給** —— 那不在這裡，在 /admin 新增使用者的表單裡（預設不勾）。
-- 使用者要的是「新增白名單時決定給不給」，不是「一律預設有」。
--
-- ## 不吃 can_manage_others 的短路
--
-- 「管不管得動別人的相簿」跟「該不該動得了軌跡資料」是兩回事，同 0013／0014。
-- 只有站長永遠是開的（程式裡 isOwner 直接放行，不看這一欄）。

ALTER TABLE User ADD COLUMN can_use_tools INTEGER NOT NULL DEFAULT 1;
