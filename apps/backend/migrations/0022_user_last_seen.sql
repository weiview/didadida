-- 0022：白名單加上「最後一次在站上出現是什麼時候」。
--
-- ## 為什麼 last_login_at 不夠
--
-- 0008 就有 last_login_at 了，而且它**確實有在寫**（Google 回呼與站長密碼登入
-- 兩條路都寫）。問題是進站 token 有效期 7 天：一個天天在看照片的人，
-- 只有在 token 過期、真的重新認證那一次才會更新那一欄。於是後台的
-- 「最後登入」看起來像壞掉的 —— 家人明明昨天才傳了照片，上面卻寫著一週前。
--
-- 兩欄的意思因此是分開的，都留著：
--   last_login_at  最後一次真的走過認證（Google 或站長密碼）
--   last_seen_at   最後一次心跳。**後台顯示的是這一欄**，因為使用者問的是
--                  「他上一次來是什麼時候」，不是「他上一次打密碼是什麼時候」
--
-- ## 順便就是「上線中」那顆綠燈
--
-- 同一欄兩個用途：夠新（PRESENCE_ONLINE_MS）就是上線中。所以不需要第二欄、
-- 也不需要第二支端點 —— `GET /api/presence` 一趟同時做「回報我還在」與
-- 「現在誰在線上」。
--
-- ## 為什麼是輪詢不是 WebSocket
--
-- 常連線在 Cloudflare 上是 Durable Objects，那是另一個計費資源，而免費額度是
-- 這個站的最高宗旨。家用相簿同時在線最多幾個人，60 秒一次輪詢的代價是
-- 每人每小時 60 次請求；五個人各看兩小時 = 600 次／天，在 Workers 的
-- 10 萬次／天裡是零頭。心跳那句 UPDATE 還帶著「40 秒內剛寫過就不寫」的條件，
-- 所以開三個分頁也只算一次寫入。
--
-- 沒有 backfill：NULL ＝ 這個人在這個功能上線後還沒回來過，後台照舊退回去
-- 顯示 last_login_at。

ALTER TABLE User ADD COLUMN last_seen_at TEXT;
