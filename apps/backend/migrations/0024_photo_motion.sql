-- 0024：Android 的「動態照片」在站上能播那一小段動畫。
--
-- ## 存的是位置，不是位元組
--
-- 那段 mp4 黏在 .jpg 的尾巴上，而**原始檔整份已經在 Drive 上了**（站上的
-- 原始檔是直傳的）。把它抽出來另外存一份等於同樣的位元組收兩次錢：
-- R2 的儲存是免費額度裡真的會被吃掉的那一格（見 0021 的 GIF），
-- 而一支動態照片的影片是 1～4MB，兩千張就好幾 GB。
-- 存一個整數，播的時候由 /api/photos/:id/motion 從 Drive 切一段 Range 出來。
--
-- ## 三個值的意思不一樣，NULL 不是 0
--
--   NULL  還沒掃過（既有的每一列都是這樣）
--   0     掃過了，不是動態照片
--   > 0   那段 mp4 從第幾個位元組開始
--
-- ⚠️ 這個分野就是 /api/admin/motion-scan 的續掃書籤 —— 「還沒掃過」
--    才要花一次 Drive 讀取，掃過的下一輪就跳過。寫成 DEFAULT 0 的話
--    整批既有照片會變成「掃過了、沒有動畫」，而那是一句假話。
--
-- ## 沒有索引
--
-- 掃描那支是 `WHERE … AND motion_offset IS NULL AND id > ?` 照主鍵往前走，
-- 走的是 Photo 的主鍵；讀取端則永遠是先拿到照片那一列才問這一欄。
-- 多一個索引只是多一份寫入成本。

ALTER TABLE Photo ADD COLUMN motion_offset INTEGER;
