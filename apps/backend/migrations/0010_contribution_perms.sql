-- 把「動別人的內容」拆成三格，不再是 can_manage_others 一顆全有全無的開關。
--
-- 起因（使用者 2026-08-14）：家人登入之後傳不了照片到別人建的相簿。
-- 那不是壞掉，是 0008 把「往別人的相簿裡塞照片」算成了「動別人的相簿」——
-- 跟改名、刪相簿同一格。但這兩件事的風險天差地遠：
--
--   新增一張照片   最壞的情況是相簿裡多一張不該有的，主人自己刪得掉
--   刪相簿／改名   別人的東西直接消失
--
-- 所以貢獻（往裡面加）預設放行，破壞性的動作維持原樣。
--
-- ## 為什麼是每人一欄，不是全站一個開關
--
-- 使用者拍板：站長要有辦法單獨關掉某一個人（小孩亂傳、某個帳號外流），
-- 全站總開關做不到這件事。UI 就掛在 /admin 既有的「可管理全站」旁邊。
--
-- ## 預設值
--
-- can_add_to_others   1 = 開。這就是這次要修的行為，新舊帳號一律享有。
-- can_reorder_others  0 = 關。相簿裡的排列是主人的版面，要另外給。
--
-- can_manage_others=1 的人不看這兩欄（程式裡直接短路成全開），
-- 所以站長與「可管理全站」的家人不受影響。

-- 可以把照片加進別人建的相簿：本機上傳 + 從 Google 相簿匯入。
-- 只涵蓋「新增」—— 加進去的那張照片 uploaded_by 記的是他，
-- 所以他自己刪得掉、相簿主人也刪得掉（見 actorOwns），不必再多一欄。
ALTER TABLE User ADD COLUMN can_add_to_others INTEGER NOT NULL DEFAULT 1;

-- 可以調整別人相簿裡的照片順序（PUT /api/photos/reorder）。
-- 跟首頁的相簿排序無關 —— 那一支是整站共用的一份，維持 can_manage_others。
ALTER TABLE User ADD COLUMN can_reorder_others INTEGER NOT NULL DEFAULT 0;
