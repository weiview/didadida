-- 0025：頭像上那張臉朝哪一邊。

-- ## 為什麼需要這一欄

-- 足跡動畫那台車會左右鏡射（往東走車頭朝右、往西走朝左，見 lib/car.ts 的 flip），
-- **但頭像不會** —— 它就是一張使用者上傳的圖。於是一張側臉朝左的頭像，
-- 在車頭朝右的那一半路上會變成「坐在車上看車尾」，看起來很怪。
--
-- 所以存的是**這張圖本來朝哪一邊**，鏡不鏡射由前端當場算：
--   鏡射 = (圖朝的那一邊 !== 車頭朝的那一邊)
-- 正臉的頭像兩個值都對，隨便挑一個就好 —— 所以預設值不必猜得準。
--
-- ⚠️ maplibre 沒有辦法把一張 icon 左右翻過來（沒有負的 icon-size，
--    也沒有 mirror 屬性）。所以鏡射版是**另外烤一張圖**（image id 尾巴加 ':m'），
--    見 lib/car.ts 的 bakeHead。一個人最多兩張，貼圖快取扛得住。

-- ## 為什麼是 TEXT 不是 0/1

-- 'left' / 'right' 讀 SQL 的時候看得懂在講什麼，而這一欄一輩子只會被讀，
-- 不會拿來做算術或索引。壞值（舊列、手動塞的）一律當 'left'，前端也再擋一次。

-- 寶寶沒有 User 那一列，他的方向記在 AppSetting.baby_avatar_facing（k/v，不需要 migration）。

ALTER TABLE User ADD COLUMN avatar_facing TEXT NOT NULL DEFAULT 'left';
